#!/usr/bin/env python3
"""Track A light-batch generator.

Emits chunks in the reusable-CI layout:
    harness/stages/stage<id>/Stage<id>Chunk_<c>.sol
    harness/stages/stage<id>/chunk_<c>.tests
    harness/stages/stage<id>/manifest.json

Batch 1 (--batch 1): combined controls for A1/A2/A6/A7, reusing the validated
ProbeBase/SINGLE template (blanket P_STORAGE_CHANGED suite is valid because the
control bodies are gated and must not write state).

Batch 2 (--batch 2): A9 UNAUTH_PULL — a scoped consent invariant
(victim balance unchanged, victim never the token mover). Uses ConsentToken.
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_stage  # noqa: E402  (HDR, SINGLE)

ROOT = os.path.dirname(HERE)
CTRL = os.path.join(ROOT, "harness", "controls")
OUTROOT = os.path.join(ROOT, "harness", "stages")


def control_code(name):
    with open(os.path.join(CTRL, name + ".hex")) as f:
        c = f.read().strip()
    return c[2:] if c.startswith("0x") else c


# ---------------------------------------------------------------- batch 1
BATCH1 = [
    ("a1_init", "MUST_FAIL", "VulnerableInit", "test_a1_vulnerable"),
    ("a1_init", "MUST_PASS", "SafeInit", "test_a1_safe"),
    ("a2_upgrade", "MUST_FAIL", "VulnerableUpgrade", "test_a2_vulnerable"),
    ("a2_upgrade", "MUST_PASS", "SafeUpgrade", "test_a2_safe"),
    ("a6_fee", "MUST_FAIL", "VulnerableFee", "test_a6_vulnerable"),
    ("a6_fee", "MUST_PASS", "SafeFee", "test_a6_safe"),
    ("a7_unchecked", "MUST_FAIL", "VulnerableUnchecked", "test_a7_vulnerable"),
    ("a7_unchecked", "MUST_PASS", "SafeUnchecked", "test_a7_safe"),
]

# ---------------------------------------------------------------- batch 2 (A9)
UNAUTH_PULL_HDR = """// SPDX-License-Identifier: UNLICENSED
// AUTO-GENERATED by gen_track_a.py -- {stage} (controls)
pragma solidity ^0.8.13;

import {{ProbeBase}} from "../src/ProbeBase.sol";

interface IPullToken {{
    function balanceOf(address) external view returns (uint256);
    function lastFrom() external view returns (address);
}}

contract Stage{stage}Chunk_{chunk} is ProbeBase {{
    address internal constant TOKEN = 0x0000000000000000000000000000000000001111;
    address internal constant VICTIM = 0x0000000000000000000000000000000000002222;
"""

UNAUTH_PULL = '''
    // {label}
    function {name}(bytes4 selector, uint256 amt, address attacker) public {{
        vm.assume(attacker != address(0));
        vm.assume(uint256(uint160(attacker)) > 0xff);
        vm.assume(attacker != address(0x7109709ECfa91a80626fF3989D68f67F5b1DD12D));
        vm.assume(attacker != address(0x000000000000000000636F6e736F6c652e6c6f67));
        address target = address(uint160(0x{base:x} + {idx}));
        vm.assume(attacker != target);
        vm.assume(attacker != VICTIM);
        vm.etch(target, hex"{code}");
        vm.deal(target, 1 ether);
        vm.etch(TOKEN, hex"{consent}");
        uint256 vb = 1_000 ether;
        vm.store(TOKEN, keccak256(abi.encode(VICTIM, uint256(0))), bytes32(vb));
        vm.store(TOKEN, keccak256(abi.encode(target, keccak256(abi.encode(VICTIM, uint256(1))))), bytes32(vb));
        vm.assume(amt <= vb);
        vm.prank(attacker);
        target.call(abi.encodeWithSelector(selector, VICTIM, amt));
        assertEq(IPullToken(TOKEN).balanceOf(VICTIM), vb, "P_UNAUTH_PULL");
        assertTrue(IPullToken(TOKEN).lastFrom() != VICTIM, "P_UNAUTH_PULL_FROM");
    }}
'''

BATCH2 = [
    ("a9_unauth_pull", "MUST_FAIL", "VulnerablePull", "test_a9_vulnerable"),
    ("a9_unauth_pull", "MUST_PASS", "SafePull", "test_a9_safe"),
]


def write_stage(stage, chunk_src, tests, cls):
    outdir = os.path.join(OUTROOT, "stage" + stage)
    os.makedirs(outdir, exist_ok=True)
    for f in os.listdir(outdir):
        if f.startswith("Stage") or f.startswith("chunk_") or f == "manifest.json":
            os.remove(os.path.join(outdir, f))
    with open(os.path.join(outdir, f"Stage{stage}Chunk_0.sol"), "w") as f:
        f.write(chunk_src)
    with open(os.path.join(outdir, "chunk_0.tests"), "w") as f:
        f.write("\n".join(tests) + "\n")
    with open(os.path.join(outdir, "manifest.json"), "w") as f:
        json.dump({"stage": stage,
                   "chunks": [{"chunk": 0, "class": cls, "tests": tests, "targets": []}]},
                  f, indent=1)
    print(f"wrote {outdir}/Stage{stage}Chunk_0.sol ({len(tests)} controls)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", type=int, default=1)
    ap.add_argument("--stage", default=None)
    args = ap.parse_args()

    if args.batch == 1:
        stage = args.stage or "tracka_batch1"
        parts, tests = [], []
        for stage_id, kind, cname, tname in BATCH1:
            parts.append(gen_stage.SINGLE.format(
                label=f"{kind} {stage_id} {cname}", name=tname,
                base=0x1000000, idx=0, code=control_code(cname)))
            tests.append(tname)
        src = gen_stage.HDR.format(stage=stage, chunk=0, cls="CONTROLS-BATCH1") + "".join(parts) + "}\n"
        write_stage(stage, src, tests, "CONTROLS-BATCH1")

    elif args.batch == 2:
        stage = args.stage or "tracka_batch2"
        consent = control_code("ConsentToken")
        parts, tests = [], []
        for stage_id, kind, cname, tname in BATCH2:
            parts.append(UNAUTH_PULL.format(
                label=f"{kind} {stage_id} {cname}", name=tname,
                base=0x2000000, idx=0, code=control_code(cname), consent=consent))
            tests.append(tname)
        src = UNAUTH_PULL_HDR.format(stage=stage, chunk=0) + "".join(parts) + "}\n"
        write_stage(stage, src, tests, "CONTROLS-BATCH2")
    else:
        raise SystemExit("--batch must be 1 or 2")


if __name__ == "__main__":
    main()
